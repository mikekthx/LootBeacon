-- Builds tests/fixtures/dungeon_run.lua from a LootBeaconProbe SavedVariables dump,
-- keeping only the events LootBeacon cares about and swapping every real player
-- name, realm and GUID for a placeholder.
-- Usage (from LootBeacon/): lua5.1.exe tests/tools/make_fixture.lua ..\LootBeaconProbe1.lua tests\fixtures\dungeon_run.lua
local source, target = arg[1], arg[2]
assert(source and target, "usage: make_fixture.lua <probe.lua> <out.lua>")
dofile(source)
local db = assert(LootBeaconProbeDB, "no LootBeaconProbeDB in " .. source)

local NAMES = { Eldwist = "Alpha", Jeremy = "Bravo", Tmow = "Charlie", Rhuna = "Delta", Freckles = "Echo" }
local REALMS = { "Majere", "Cull", "Mcrhunface", "Breeze" }
local KEEP = {
	START_LOOT_ROLL = true, CANCEL_LOOT_ROLL = true, CANCEL_ALL_LOOT_ROLLS = true,
	LOOT_HISTORY_UPDATE_DROP = true, LOOT_HISTORY_UPDATE_ENCOUNTER = true, LOOT_ROLLS_COMPLETE = true,
	CHAT_MSG_LOOT = true, PLAYER_ENTERING_WORLD = true,
}

local guids, nextGuid = {}, 0
local function Scrub(text)
	text = text:gsub("Player%-%d+%-%x+", function(guid)
		if not guids[guid] then
			nextGuid = nextGuid + 1
			guids[guid] = ("Player-1-%08X"):format(nextGuid)
		end
		return guids[guid]
	end)
	for real, fake in pairs(NAMES) do
		text = text:gsub(real, fake)
	end
	for _, realm in ipairs(REALMS) do
		text = text:gsub("%-" .. realm, "-Realm")
	end
	return text
end

local function Copy(value)
	if type(value) == "string" then return Scrub(value) end
	if type(value) ~= "table" then return value end
	local out = {}
	for key, inner in pairs(value) do
		out[Copy(key)] = Copy(inner)
	end
	return out
end

local function Serialize(value, indent, out)
	local kind = type(value)
	if kind == "string" then
		out[#out + 1] = ("%q"):format(value)
	elseif kind == "number" or kind == "boolean" then
		out[#out + 1] = tostring(value)
	elseif kind == "table" then
		out[#out + 1] = "{\n"
		local keys = {}
		for key in pairs(value) do keys[#keys + 1] = key end
		table.sort(keys, function(a, b)
			if type(a) == type(b) then return a < b end
			return type(a) == "number"
		end)
		for _, key in ipairs(keys) do
			local keyText = type(key) == "string" and ("%q"):format(key) or tostring(key)
			out[#out + 1] = indent .. "\t[" .. keyText .. "] = "
			Serialize(value[key], indent .. "\t", out)
			out[#out + 1] = ",\n"
		end
		out[#out + 1] = indent .. "}"
	else
		error("can't serialize a " .. kind)
	end
end

local entries = {}
for _, entry in ipairs(db.log) do
	if KEEP[entry.kind] then
		local data = entry.data or {}
		data.context = nil
		data.textIsSecret, data.canAccess = nil, nil
		if entry.kind == "CHAT_MSG_LOOT" then
			data.args = { n = 1, data.args[1] }
		end
		entries[#entries + 1] = Copy({ t = entry.t, kind = entry.kind, data = data })
	end
end

local out = {}
Serialize(entries, "", out)
local text = "-- Generated by tests/tools/make_fixture.lua from a LootBeaconProbe log. Do not edit by hand.\nreturn "
	.. table.concat(out) .. "\n"

for real in pairs(NAMES) do
	assert(not text:find(real, 1, true), "fixture still contains the name " .. real)
end
for _, realm in ipairs(REALMS) do
	assert(not text:find(realm, 1, true), "fixture still contains the realm " .. realm)
end
assert(not text:find("Player%-4%d%d%d%-"), "fixture still contains a real GUID")

local file = assert(io.open(target, "wb"))
file:write(text)
file:close()
print(("wrote %d entries to %s"):format(#entries, target))
